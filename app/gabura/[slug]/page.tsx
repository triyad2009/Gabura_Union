export function generateStaticParams() {
  return Object.keys(pages).map((slug) => ({ slug }));
}

export default async function Page({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const data = pages[slug];

  if (!data) notFound();

  return (
    <main>
      <header className="nav">
        <div
          className="wrap"
          style={{
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
          }}
        >
          <Link className="brand" href="/">
            GABURA ARCHIVE
          </Link>
          <Link className="navlink" href="/gabura">
            ← GABURA
          </Link>
        </div>
      </header>

      <section className="hero">
        <div className="wrap">
          <div className="eyebrow">Section 01 / GABURA</div>
          <h1>{data.title}</h1>
          <p>{data.intro}</p>
        </div>
      </section>

      <section className="section">
        <div className="wrap">
          {data.facts && (
            <div className="grid">
              {data.facts.map((fact) => (
                <div className="card" key={fact.label}>
                  <small>{fact.label}</small>
                  <h2>{fact.value}</h2>
                </div>
              ))}
            </div>
          )}

          {data.sections.map((section) => (
            <article key={section.heading} style={{ maxWidth: 850, marginBottom: 58 }}>
              <div className="eyebrow">{section.heading}</div>
              {section.paragraphs.map((paragraph) => (
                <p className="muted" style={{ fontSize: 18 }} key={paragraph}>
                  {paragraph}
                </p>
              ))}
            </article>
          ))}

          {data.sourceNote && (
            <aside
              style={{
                borderTop: "1px solid var(--line)",
                paddingTop: 28,
                maxWidth: 850,
              }}
            >
              <div className="eyebrow">Source Note</div>
              <p className="muted">{data.sourceNote}</p>
            </aside>
          )}
        </div>
      </section>
    </main>
  );
}
